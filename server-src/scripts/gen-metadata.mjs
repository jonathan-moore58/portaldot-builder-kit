// Saves each network's runtime metadata inside the source, compressed, so the server does not have
// to download more than half a megabyte from the public node at the start of every session.
//
// It saves the newest metadata version the node offers (16, 15 or 14). Version 14, which the old
// state_getMetadata request returns, lists no runtime APIs, so with it @polkadot/api would not
// offer api.call.reviveApi at all. Versions 15 and 16 carry those definitions.
//
// The server uses a saved copy only when the live chain reports the same genesis hash and runtime
// version. After a runtime upgrade it downloads the new metadata by itself; run this script again
// then, and rebuild, to make sessions fast again.
//
// Usage (from server-src): node scripts/gen-metadata.mjs
import { writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const NETWORKS = {
  testnet: 'https://test-node-v3.portaldot.dev',
  mainnet: 'https://live-v3-node.portaldot.dev',
};

async function rpc(url, method, params = []) {
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }),
    signal: AbortSignal.timeout(120_000),
  });
  if (!res.ok) throw new Error(`${method}: HTTP ${res.status}`);
  const body = await res.json();
  if (body.error) throw new Error(`${method}: ${body.error.message}`);
  return body.result;
}

// A SCALE compact integer at the start of a buffer: [value, bytes used].
function compact(buf) {
  const mode = buf[0] & 3;
  if (mode === 0) return [buf[0] >> 2, 1];
  if (mode === 1) return [buf.readUInt16LE(0) >> 2, 2];
  if (mode === 2) return [buf.readUInt32LE(0) >>> 2, 4];
  throw new Error('a compact integer larger than this script expects');
}

const out = {};
for (const [key, url] of Object.entries(NETWORKS)) {
  const [genesis, version, versionsHex] = await Promise.all([rpc(url, 'chain_getBlockHash', [0]), rpc(url, 'state_getRuntimeVersion'), rpc(url, 'state_call', ['Metadata_metadata_versions', '0x'])]);
  const list = Buffer.from(versionsHex.slice(2), 'hex');
  const [count, offset] = compact(list);
  const offered = Array.from({ length: count }, (_, i) => list.readUInt32LE(offset + 4 * i));
  const usable = offered.filter((v) => [14, 15, 16].includes(v));
  if (!usable.length) throw new Error(`${key}: the node offers metadata versions ${offered.join(', ')}, none of which this script knows`);
  const best = Math.max(...usable);

  const arg = Buffer.alloc(4);
  arg.writeUInt32LE(best);
  // The answer is an Option of the metadata bytes: one byte (1 = present), a compact length, then the bytes.
  const answer = Buffer.from((await rpc(url, 'state_call', ['Metadata_metadata_at_version', `0x${arg.toString('hex')}`])).slice(2), 'hex');
  if (answer[0] !== 1) throw new Error(`${key}: the node has no metadata of version ${best}`);
  const [length, used] = compact(answer.subarray(1));
  const raw = answer.subarray(1 + used, 1 + used + length);
  if (raw.length !== length || raw.subarray(0, 4).toString('latin1') !== 'meta' || raw[4] !== best) throw new Error(`${key}: the metadata bytes do not look right`);

  const packed = gzipSync(raw, { level: 9 });
  out[key] = { genesis, specName: version.specName, specVersion: version.specVersion, metadataVersion: best, bytes: raw.length, gzipBase64: packed.toString('base64') };
  console.log(`${key}: ${version.specName} spec ${version.specVersion}, metadata version ${best} (offered: ${offered.join(', ')}), ${raw.length} bytes, ${packed.length} bytes compressed`);
}

const today = new Date().toISOString().slice(0, 10);
const body = `// GENERATED by scripts/gen-metadata.mjs on ${today}. Do not edit by hand.
// Each network's runtime metadata, gzip-compressed and base64-encoded.

export interface SavedMetadata {
  genesis: string;
  specName: string;
  specVersion: number;
  /** The metadata format version (15 and 16 list the runtime APIs; 14 does not). */
  metadataVersion: number;
  /** Size of the metadata before compression. */
  bytes: number;
  gzipBase64: string;
}

export const SAVED_METADATA: Record<string, SavedMetadata> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/generated/metadata.ts', import.meta.url), body);
console.log(`wrote src/generated/metadata.ts (${(body.length / 1024).toFixed(0)} KB)`);
